// Типограф: неразрывные пробелы по правилам русского набора. Работает при сборке,
// по готовому HTML и только по тексту между тегами (атрибуты, скрипты и стили не трогает).
//   1. Короткие слова (предлоги, союзы, частицы до 3 букв) не остаются в конце строки:
//      «в Ижевске», «и таможня», «до ключей», «под ключ».
//   2. Число не отрывается от слова или единицы после него: «3 рабочих дня», «160 л.с.», «4,9 на».
//   3. Тире не начинает строку: «машина — в канале».
//   4. «ли», «же», «бы» не уходят на новую строку от слова перед ними.
const SHORT =
  'а|в|и|к|о|с|у|я|во|да|до|за|из|ко|на|не|ни|но|об|от|по|со|то|без|для|или|над|под|при|про|что|как|его|её|их|все|всё';
const NBSP = ' ';

const shortWord = new RegExp(`(^|[\\s\\u00a0(«"])(${SHORT}) +`, 'giu');
const rules = [
  // 2. число + пробел + слово или единица
  [/(\d) +(?=[\p{L}%₽$€№])/gu, `$1${NBSP}`],
  // 3. пробел перед тире
  [/ +(—|–)(?=\s)/g, `${NBSP}$1`],
  // 4. частицы
  [/ +(ли|же|ж|бы|б)(?=[\s.,!?:;)]|$)/gu, `${NBSP}$1`],
];

function typoText(text) {
  let out = text;
  // Правило 1 дважды: «и в Казани» — два коротких слова подряд
  for (let pass = 0; pass < 2; pass++) out = out.replace(shortWord, `$1$2${NBSP}`);
  for (const [re, to] of rules) out = out.replace(re, to);
  return out;
}

export function typograph(html) {
  let skip = 0; // внутри <script>, <style>, <textarea>, <pre>
  return html
    .split(/(<[^>]+>)/)
    .map((part) => {
      if (part.startsWith('<')) {
        const m = part.match(/^<(\/?)(script|style|textarea|pre)\b/i);
        if (m) skip += m[1] ? -1 : 1;
        return part;
      }
      return skip > 0 || !part.trim() ? part : typoText(part);
    })
    .join('');
}

// Ссылка в бота для боевого режима. Для MAX и ВКонтакте адреса бота пока нет: [заполнить]
export function botUrl(id, ctx = {}) {
  const tag = ACTIONS[id]?.tag?.(ctx) ?? id;
  return `https://t.me/${BOT}?start=${encodeURIComponent(tag)}`;
}

// Атрибуты кнопки действия. В демо — кнопка, открывающая модалку; в бою — ссылка в бота.
// key — мессенджер, на который нажали: в модалке он подсвечивается.
export function actionAttrs(id, { key = 'telegram', ctx = {} } = {}) {
  const data = `data-action="${id}" data-key="${key}" data-ctx="${JSON.stringify(ctx).replace(/"/g, '&quot;')}"`;
  if (DEMO_MODE) return { tag: 'button', attrs: `type="button" ${data} aria-haspopup="dialog"` };
  return { tag: 'a', attrs: `href="${botUrl(id, ctx)}" target="_blank" rel="noopener" ${data}` };
}
